"""Reporting helpers for stage-output inspection notebooks.

The notebooks under ``playbooks/report/`` stay lean: they narrate and render,
while the non-trivial work of turning a stage's primary artifact into tidy
frames and figures lives here. This is deliberately distinct from
:mod:`gnomad_meb.pipeline.report`, which renders a *run*'s step statuses
(ADR-0014); a *stage report* opens the artifact a stage produced.

The package is organised **one module per pipeline stage**: each stage owns a
single module holding both its collectors and its plot builders
(:mod:`gnomad_meb.reporting.vds` for ``vds create``,
:mod:`gnomad_meb.reporting.sample_qc` for Sample QC,
:mod:`gnomad_meb.reporting.variant_qc` for Variant QC,
:mod:`gnomad_meb.reporting.annotation` for Annotation), with the shared plotting
vocabulary in :mod:`gnomad_meb.reporting.theme`.

Importing this package reaches Hail through the stage modules; it is never
imported by ``gnomad_meb`` itself, so ``import gnomad_meb`` stays free of the
hail stack.
"""

